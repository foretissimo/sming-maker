#!/usr/bin/env bash

# ==============================================================================
# 🌲 포레스텔라 스밍 메이커 (Sming Maker) 로컬 개발 서버 시작 스크립트
# ==============================================================================

# 스크립트가 위치한 디렉토리로 이동
cd "$(dirname "$0")" || exit 1

echo "=================================================="
echo "🌲 포레스텔라 스밍 메이커 로컬 서버 시작"
echo "=================================================="

# 1. Git pull 최신화 (음총팀 데이터 병합 및 최신 코드 동기화)
echo ""
echo "📥 [1/3] 최신 코드 및 음원 데이터 동기화 (git pull origin main)..."
git pull origin main

# 2. 의존성 패키지(node_modules) 설치 확인
echo ""
echo "📦 [2/3] 의존성 패키지 확인 중..."
if [ ! -d "node_modules" ]; then
  echo "⚠️ node_modules 폴더가 없습니다. npm install을 진행합니다..."
  npm install
else
  echo "✅ 패키지 확인 완료."
fi

# 3. 로컬 Vite 개발 서버 실행 (브라우저 자동 열기 및 로컬 네트워크 호스트 지원)
echo ""
echo "🚀 [3/3] 로컬 개발 서버를 실행하고 브라우저를 엽니다..."
echo "       - 종료하려면 터미널에서 Ctrl + C 를 누르세요."
echo "=================================================="
echo ""

npm run dev -- --open --host
